/**
 * Translation helper function
 * @param {string} key - Dictionary key
 * @param {string} lang - 'ar' | 'fr' | 'en'
 * @param {object} params - Optional interpolation parameters like { workshop: '...', model: '...' }
 * @returns {string} Translated string or key fallback
 */
function getTranslation(key, lang = 'ar', params = {}) {
    const currentLangDict = TRANSLATIONS[lang] || TRANSLATIONS['ar'];
    let text = currentLangDict[key] || TRANSLATIONS['ar'][key] || key;

    // Interpolate {param} if provided
    if (params && typeof params === 'object') {
        Object.keys(params).forEach(pKey => {
            text = text.replace(new RegExp(`\\{${pKey}\\}`, 'g'), params[pKey]);
        });
    }

    return text;
}

